package StringPractice;
import java.util.*;
public class Q1ReadString{
    public static void main(String[] args) {
        Scanner sc=new Scanner(System.in);
        String str=sc.next();
        System.out.println(str);
        sc.nextLine();
        String strl=sc.nextLine();
        System.out.println(strl);
        sc.close();
    }
}